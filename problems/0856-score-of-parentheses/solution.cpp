// 856. Score of Parentheses [Medium]
// https://leetcode.com/problems/score-of-parentheses/
// Language: C++ | Runtime: 0 ms | Memory: 7.8 MB

class Solution {
public:
    int scoreOfParentheses(string s) {
        int score = 0, depth = 0;
        for (int i = 0; i < s.size(); ++i) {
            if (s[i] == '(') {
                ++depth;
            } else {
                --depth;
                if (s[i - 1] == '(') {
                    score += 1 << depth;
                }
            }
        }
        return score;
    }
};
